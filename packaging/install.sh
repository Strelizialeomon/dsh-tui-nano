#!/bin/sh
# Install the dsh-tui-nano payload into a user-local prefix.
#
# The installer never writes credentials, sessions, or global instructions and
# never replaces another product's dsh profile. Re-running it is idempotent and
# is the supported upgrade path.
set -eu

here="$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)"

usage() {
  cat <<'USAGE'
用法：install.sh [选项]

  --dsh-home <path>     官方 dsh home（默认 $DSH_HOME 或 ~/.dsh）
  --data-root <path>    Nano 数据根（默认 ~/.dsh-tui-nano）
  --install-root <path> 安装目录（默认 ~/.local/share/dsh-tui-nano）
  --bin-dir <path>      入口目录（默认 ~/.local/bin）
  --dsh-bin <path>      dsh 可执行文件（默认 PATH 中的 dsh）
  --no-profile-install  只安装文件，不运行官方 profile 安装
  --json                输出一行 JSON 安装凭据
  -h, --help            显示本帮助
USAGE
}

dsh_home="${DSH_HOME:-$HOME/.dsh}"
data_root="${NANO_DATA_ROOT:-$HOME/.dsh-tui-nano}"
install_root="${NANO_INSTALL_ROOT:-${XDG_DATA_HOME:-$HOME/.local/share}/dsh-tui-nano}"
bin_dir="${NANO_BIN_DIR:-$HOME/.local/bin}"
dsh_bin="${NANO_DSH:-}"
profile_install=1
json=0

while [ $# -gt 0 ]; do
  case "$1" in
    --dsh-home) dsh_home="$2"; shift 2 ;;
    --data-root) data_root="$2"; shift 2 ;;
    --install-root) install_root="$2"; shift 2 ;;
    --bin-dir) bin_dir="$2"; shift 2 ;;
    --dsh-bin) dsh_bin="$2"; shift 2 ;;
    --no-profile-install) profile_install=0; shift ;;
    --json) json=1; shift ;;
    -h|--help) usage; exit 0 ;;
    *) echo "install.sh: 未知参数 $1" >&2; usage >&2; exit 2 ;;
  esac
done

fail() {
  echo "install.sh: $*" >&2
  exit 1
}

node_bin="${NANO_NODE:-}"
if [ -z "$node_bin" ]; then
  node_bin="$(command -v node 2>/dev/null || true)"
fi
[ -n "$node_bin" ] || fail "未找到 node。请安装 Node（已验证 v24.18.0），或设置 NANO_NODE=/path/to/node。"

node_version="$("$node_bin" --version)"
node_major="$(printf '%s' "$node_version" | sed 's/^v//' | cut -d. -f1)"
case "$node_major" in
  ''|*[!0-9]*) fail "无法解析 node 版本：$node_version" ;;
esac
[ "$node_major" -ge 22 ] || fail "Node $node_version 低于最低要求 v22；请升级 Node 后重试。"

manifest="$here/manifest.json"
[ -f "$manifest" ] || fail "安装包缺少 manifest.json：$manifest"

version="$("$node_bin" -e 'process.stdout.write(require(process.argv[1]).version)' "$manifest")"
bridge_version="$("$node_bin" -e 'process.stdout.write(require(process.argv[1]).bridgeVersion)' "$manifest")"
official_version="$("$node_bin" -e 'process.stdout.write(require(process.argv[1]).official.version)' "$manifest")"
official_source="$("$node_bin" -e 'process.stdout.write(require(process.argv[1]).official.source)' "$manifest")"

if [ -z "$dsh_bin" ]; then
  dsh_bin="$(command -v dsh 2>/dev/null || true)"
fi
[ -n "$dsh_bin" ] || fail "未找到 dsh。请安装官方 dsh ${official_version}，或传 --dsh-bin /path/to/dsh。"

dsh_version="$("$dsh_bin" --version 2>/dev/null || true)"
[ -n "$dsh_version" ] || fail "无法运行 $dsh_bin --version；请检查 dsh 安装。"
[ "$dsh_version" = "$official_version" ] || fail "官方 dsh 版本不符：当前 ${dsh_version}，需要 ${official_version}。请安装精确版本后重试：npm install -g @deepseek-ai/dsh@$official_version"

[ -x "$here/bin/nano" ] || fail "安装包缺少可执行文件：$here/bin/nano"
[ -f "$here/lib/bridge/package.json" ] || fail "安装包缺少桥接包：$here/lib/bridge"
[ -f "$here/lib/protocol/package.json" ] || fail "安装包缺少协议包：$here/lib/protocol"
[ -f "$here/SHA256SUMS" ] || fail "安装包缺少 SHA256SUMS；无法核对产物完整性。"

payload_bridge_version="$("$node_bin" -e 'process.stdout.write(require(process.argv[1]).version)' "$here/lib/bridge/package.json")"
[ "$payload_bridge_version" = "$bridge_version" ] || fail "桥接包版本不符：安装包 ${payload_bridge_version}，manifest ${bridge_version}。"

umask 077
mkdir -p "$install_root" "$bin_dir" "$data_root"
chmod 700 "$install_root" "$data_root" 2>/dev/null || true

target="$install_root/$version"
verify_payload() {
  ( cd "$1" && shasum -a 256 -c SHA256SUMS >/dev/null 2>&1 )
}

replaced=0
if [ -d "$target" ] && verify_payload "$target"; then
  : # already installed and verified; reuse
else
  tmp="$install_root/.install-$version-$$"
  rm -rf "$tmp"
  mkdir -p "$tmp"
  cp -R "$here/." "$tmp/"
  rm -rf "$tmp/dist"
  verify_payload "$tmp" || { rm -rf "$tmp"; fail "复制后的文件校验失败；安装包可能已损坏。"; }
  if [ -d "$target" ]; then
    old="$install_root/.old-$version-$$"
    rm -rf "$old"
    mv "$target" "$old"
    mv "$tmp" "$target"
    rm -rf "$old"
    replaced=1
  else
    mv "$tmp" "$target"
  fi
fi

current_tmp="$install_root/.current-$$"
rm -f "$current_tmp"
ln -s "$version" "$current_tmp"
mv -f "$current_tmp" "$install_root/current"

wrapper="$bin_dir/nano"
wrapper_tmp="$bin_dir/.nano-$$"
cat > "$wrapper_tmp" <<WRAPPER
#!/bin/sh
# Generated by dsh-tui-nano $version. Re-run install.sh to upgrade.
set -eu
NANO_HOME='$target'
if [ ! -x "\$NANO_HOME/bin/nano" ]; then
  echo "nano: 安装目录缺失：\${NANO_HOME}；请重新运行 install.sh" >&2
  exit 1
fi
if [ ! -f "\$NANO_HOME/lib/bridge/package.json" ]; then
  echo "nano: 桥接包缺失：\$NANO_HOME/lib/bridge；请重新运行 install.sh" >&2
  exit 1
fi
node_bin="\${NANO_NODE:-\$(command -v node 2>/dev/null || true)}"
if [ -z "\$node_bin" ]; then
  echo "nano: 未找到 node；请安装 Node 或设置 NANO_NODE" >&2
  exit 1
fi
actual_bridge="\$("\$node_bin" -e 'process.stdout.write(require(process.argv[1]).version)' "\$NANO_HOME/lib/bridge/package.json")"
if [ "\$actual_bridge" != '$bridge_version' ]; then
  echo "nano: 桥接包版本不符：当前 \${actual_bridge}，需要 ${bridge_version}；请重新运行 install.sh" >&2
  exit 1
fi
export NANO_BRIDGE_PACKAGE="\$NANO_HOME/lib/bridge"
exec "\$NANO_HOME/bin/nano" "\$@"
WRAPPER
chmod 755 "$wrapper_tmp"
mv -f "$wrapper_tmp" "$wrapper"

profile_dir="$dsh_home/profiles/dsh-tui-nano"
if [ "$profile_install" -eq 1 ]; then
  "$node_bin" "$target/lib/bridge/profile/install.mjs" \
    --dsh-home "$dsh_home" \
    --data-root "$data_root" \
    --bridge-package "$target/lib/bridge" \
    --dsh-bin "$dsh_bin" \
    --json >/dev/null
fi

installed_at="$(date -u +%Y-%m-%dT%H:%M:%SZ)"
sums_sha="$("$node_bin" -e '
const { createHash } = require("node:crypto")
const fs = require("node:fs")
const file = process.argv[1]
process.stdout.write(createHash("sha256").update(fs.readFileSync(file)).digest("hex"))
' "$target/SHA256SUMS")"
receipt="$install_root/install-receipt.json"
cat > "$receipt" <<RECEIPT
{
  "name": "dsh-tui-nano",
  "version": "$version",
  "installedAt": "$installed_at",
  "installRoot": "$install_root",
  "target": "$target",
  "entrypoint": "$wrapper",
  "dataRoot": "$data_root",
  "dshHome": "$dsh_home",
  "profile": "dsh-tui-nano",
  "profileDir": "$profile_dir",
  "official": {
    "version": "$official_version",
    "source": "$official_source"
  },
  "node": "$node_version",
  "bridgeVersion": "$bridge_version",
  "payloadSumsSha256": "$sums_sha",
  "replacedExistingFiles": $replaced
}
RECEIPT

if [ "$json" -eq 1 ]; then
  cat "$receipt"
  exit 0
fi

echo "dsh-tui-nano $version 已安装"
echo "  入口：      $wrapper"
echo "  安装目录：  $target"
echo "  数据根：    $data_root"
echo "  profile：   $profile_dir"
echo "  配置来源：  $profile_dir/package.json（官方 profile；未覆盖其他 profile）"
echo "  凭据来源：  ${dsh_home}（官方凭据，未复制）"
echo "  全局指令：  由官方 agent-instructions 加载；在应用内 Alt+R 查看实际来源"
echo "  官方版本：  dsh $official_version"
echo "  安装凭据：  $receipt"
if [ "$replaced" -eq 1 ]; then
  echo "  本次替换了同版本安装目录（重装/升级演练）"
fi
