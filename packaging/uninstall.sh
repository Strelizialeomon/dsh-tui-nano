#!/bin/sh
# Remove the dsh-tui-nano program files.
#
# By default this keeps the Nano data root (sessions, runtime data) and the
# official dsh home untouched. Deleting either requires an explicit flag.
set -eu

install_root="${NANO_INSTALL_ROOT:-${XDG_DATA_HOME:-$HOME/.local/share}/dsh-tui-nano}"
bin_dir="${NANO_BIN_DIR:-$HOME/.local/bin}"
data_root="${NANO_DATA_ROOT:-$HOME/.dsh-tui-nano}"
dsh_home="${DSH_HOME:-$HOME/.dsh}"
purge_data=0
remove_profile=0
json=0

usage() {
  cat <<'USAGE'
用法：uninstall.sh [选项]

  --install-root <path>  安装目录（默认 ~/.local/share/dsh-tui-nano）
  --bin-dir <path>       入口目录（默认 ~/.local/bin）
  --data-root <path>     Nano 数据根（默认 ~/.dsh-tui-nano）
  --dsh-home <path>      官方 dsh home（默认 $DSH_HOME 或 ~/.dsh）
  --purge-data           显式删除 Nano 数据根（会删除会话与运行数据）
  --remove-profile       显式删除 dsh-tui-nano profile
  --json                 输出一行 JSON 结果
  -h, --help             显示本帮助
USAGE
}

while [ $# -gt 0 ]; do
  case "$1" in
    --install-root) install_root="$2"; shift 2 ;;
    --bin-dir) bin_dir="$2"; shift 2 ;;
    --data-root) data_root="$2"; shift 2 ;;
    --dsh-home) dsh_home="$2"; shift 2 ;;
    --purge-data) purge_data=1; shift ;;
    --remove-profile) remove_profile=1; shift ;;
    --json) json=1; shift ;;
    -h|--help) usage; exit 0 ;;
    *) echo "uninstall.sh: 未知参数 $1" >&2; usage >&2; exit 2 ;;
  esac
done

wrapper="$bin_dir/nano"
profile_dir="$dsh_home/profiles/dsh-tui-nano"

# Refuse before deleting anything when the requested profile is not ours.
if [ "$remove_profile" -eq 1 ] && [ -d "$profile_dir" ]; then
  if ! grep -q '"name": "dsh-profile-dsh-tui-nano"' "$profile_dir/package.json" 2>/dev/null ||
     ! grep -q '@dsh-tui-nano/bridge' "$profile_dir/package.json" 2>/dev/null; then
    echo "uninstall.sh: $profile_dir 不属于 dsh-tui-nano，拒绝删除" >&2
    exit 1
  fi
fi

# Refuse to delete an arbitrary directory that this installer did not create.
if [ -d "$install_root" ] && [ ! -f "$install_root/install-receipt.json" ]; then
  echo "uninstall.sh: $install_root 缺少 install-receipt.json，拒绝删除" >&2
  exit 1
fi

removed_wrapper=0
if [ -f "$wrapper" ] && grep -q 'Generated by dsh-tui-nano' "$wrapper" 2>/dev/null; then
  rm -f "$wrapper"
  removed_wrapper=1
fi

removed_install=0
if [ -d "$install_root" ]; then
  rm -rf "$install_root"
  removed_install=1
fi

removed_profile=0
if [ "$remove_profile" -eq 1 ] && [ -d "$profile_dir" ]; then
  rm -rf "$profile_dir"
  removed_profile=1
fi

removed_data=0
if [ "$purge_data" -eq 1 ] && [ -d "$data_root" ]; then
  rm -rf "$data_root"
  removed_data=1
fi

if [ "$json" -eq 1 ]; then
  retained_data="\"$data_root\""
  [ "$removed_data" -eq 1 ] && retained_data="null"
  retained_profile="\"$profile_dir\""
  [ "$removed_profile" -eq 1 ] && retained_profile="null"
  printf '{"removedEntrypoint":%s,"removedInstallRoot":%s,"removedProfile":%s,"removedDataRoot":%s,"retainedDataRoot":%s,"retainedProfile":%s,"retainedDshHome":"%s"}\n' \
    "$removed_wrapper" "$removed_install" "$removed_profile" "$removed_data" "$retained_data" "$retained_profile" "$dsh_home"
  exit 0
fi

echo "dsh-tui-nano 已卸载程序文件"
echo "  入口已移除：$removed_wrapper"
echo "  安装目录已移除：$removed_install"
if [ "$removed_profile" -eq 1 ]; then
  echo "  profile 已删除：$profile_dir"
else
  echo "  profile 保留：${profile_dir}（删除需显式 --remove-profile）"
fi
if [ "$removed_data" -eq 1 ]; then
  echo "  数据根已删除：$data_root"
else
  echo "  数据根保留：${data_root}（会话与运行数据未删除；删除需显式 --purge-data）"
fi
echo "  官方 dsh home 保留：${dsh_home}（凭据、其他 profile 与会话未触碰）"
